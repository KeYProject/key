package de.uka.ilkd.key.rule.metaconstruct;

import java.util.ArrayList;
import java.util.List;

import de.uka.ilkd.key.java.KeYJavaASTFactory;
import de.uka.ilkd.key.java.Services;
import de.uka.ilkd.key.java.ast.ProgramElement;
import de.uka.ilkd.key.java.ast.Statement;
import de.uka.ilkd.key.java.ast.declaration.LocalVariableDeclaration;
import de.uka.ilkd.key.java.ast.declaration.VariableSpecification;
import de.uka.ilkd.key.java.ast.expression.Expression;
import de.uka.ilkd.key.java.ast.reference.TypeRef;
import de.uka.ilkd.key.java.ast.statement.Continue;
import de.uka.ilkd.key.java.ast.statement.LoopStatement;
import de.uka.ilkd.key.java.ast.statement.While;
import de.uka.ilkd.key.java.visitor.BindingVariableVisitor;
import de.uka.ilkd.key.java.visitor.CreatingASTVisitor;
import de.uka.ilkd.key.java.visitor.OuterBreakContinueAndReturnCollector;
import de.uka.ilkd.key.logic.ProgramElementName;
import de.uka.ilkd.key.logic.op.LocationVariable;
import de.uka.ilkd.key.logic.op.ProgramVariable;
import de.uka.ilkd.key.rule.inst.SVInstantiations;
import de.uka.ilkd.key.speclang.LoopContract;

import org.key_project.logic.op.sv.SchemaVariable;
import org.key_project.util.ExtList;
import org.key_project.util.collection.ImmutableArray;
import org.key_project.util.collection.ImmutableList;

/**
 * Rewrites a loop with a binding guard into an ordinary loop with a fresh boolean guard.
 *
 * <p>
 * For {@code while (e) S}, the result is
 *
 * <pre>
 * boolean b = e;
 * while (b) {
 *     whenTrue(e) declarations;
 *     S with target continues rewritten to { b = e; continue; }
 *     b = e;
 * }
 * whenFalse(e) declarations, if the body has no unlabeled break
 * </pre>
 *
 * The rewritten guard is a plain variable, so the rewrite rule cannot fire on the recursive loop
 * generated by unwinding.
 *
 * @author Alexander Weigl
 */
@TransformerMeta(name = "#rewritePatternBlock")
public final class PatternLoopRewriter extends ProgramTransformer {
    private final SchemaVariable statementsSV;

    /**
     * @param statementsSV the statement list of the block to rewrite
     */
    public PatternLoopRewriter(ProgramElement statementsSV) {
        super("#rewritePatternBlock", statementsSV);
        this.statementsSV = (SchemaVariable) statementsSV;
    }

    @Override
    public ImmutableList<ProgramElement> getArguments() {
        return ImmutableList.of((ProgramElement) statementsSV);
    }

    @Override
    public ProgramElement[] transform(ProgramElement pe, Services services,
            SVInstantiations svInst) {
        var statements = (ImmutableArray<Statement>) svInst.getInstantiation(statementsSV);
        var boolVar = freshBoolean(services);
        var result = new ArrayList<Statement>();
        boolean rewritten = false;
        for (Statement statement : statements) {
            if (!rewritten && statement instanceof LoopStatement loop
                    && BindingVariableVisitor.binds(loop.getGuardExpression())) {
                for (ProgramElement element : rewriteLoop(loop, boolVar, services)) {
                    result.add((Statement) element);
                }
                rewritten = true;
            } else {
                result.add(statement);
            }
        }
        if (!rewritten) {
            var unchanged = new ProgramElement[statements.size()];
            for (int i = 0; i < statements.size(); i++) {
                unchanged[i] = statements.get(i);
            }
            return unchanged;
        }
        return result.toArray(ProgramElement[]::new);
    }

    private static ProgramElement[] rewriteLoop(LoopStatement loop, ProgramVariable boolVar,
            Services services) {
        if (loop instanceof While whileLoop) {
            return rewriteWhile(whileLoop, boolVar, services);
        }
        throw new UnsupportedOperationException(
            "Unsupported loop kind in #rewritePatternBlock: " + loop.getClass().getSimpleName());
    }

    private static ProgramVariable freshBoolean(Services services) {
        var booleanType = services.getJavaInfo().getKeYJavaType("boolean");
        var name = new ProgramElementName(services.getTermBuilder().newName("b"));
        var variable = new LocationVariable(name, new TypeRef(booleanType));
        services.getNamespaces().programVariables().addSafely(variable);
        return variable;
    }

    /**
     * Rewrites a {@code while} loop. The returned array is meant to be spliced into the enclosing
     * statement block.
     */
    static ProgramElement[] rewriteWhile(While loop, ProgramVariable boolVar,
            Services services) {
        Expression guard = loop.getGuardExpression();
        Statement body = loop.getBody();
        var bindings = BindingVariableVisitor.analyze(guard);

        Statement rewrittenBody = rewriteContinues(body, boolVar, guard, List.of(), services);
        var bodyStatements = new ArrayList<Statement>();
        bodyStatements.addAll(List.of(BindingVariableVisitor.toStatements(bindings.whenTrue())));
        addBodyStatements(bodyStatements, rewrittenBody);
        bodyStatements.add(KeYJavaASTFactory.assign(boolVar, guard));

        While newLoop = KeYJavaASTFactory.whileLoop(boolVar,
            KeYJavaASTFactory.block(bodyStatements.toArray(Statement[]::new)),
            loop.getPositionInfo());
        copyLoopSpec(loop, newLoop, services);

        var result = new ArrayList<Statement>();
        result.add(booleanDeclaration(boolVar, guard, services));
        result.add(newLoop);
        if (!bindings.whenFalse().isEmpty() && !hasUnlabeledBreak(body, services)) {
            result.addAll(List.of(BindingVariableVisitor.toStatements(bindings.whenFalse())));
        }
        return result.toArray(ProgramElement[]::new);
    }

    /**
     * Rewrites unlabeled continues that target the loop currently being rewritten.
     *
     * <p>
     * A continue inside a nested loop targets that loop and is left untouched. A continue inside a
     * switch still targets the surrounding loop and is rewritten.
     */
    static Statement rewriteContinues(Statement body, ProgramVariable boolVar,
            Expression guard, List<Statement> prefix, Services services) {
        var rewriter = new ContinueRewriter(body, boolVar, guard, prefix, services);
        rewriter.start();
        return (Statement) rewriter.result();
    }

    /**
     * Returns whether {@code body} contains an unlabeled break at loop depth zero, i.e. a break
     * for which the surrounding loop is the target.
     */
    static boolean hasUnlabeledBreak(Statement body, Services services) {
        var collector = new OuterBreakContinueAndReturnCollector(body, List.of(), services);
        collector.collect();
        return collector.getBreaks().stream().anyMatch(b -> b.getLabel() == null);
    }

    /**
     * Copies the loop specification and loop contracts from the original loop to the rewritten
     * loop.
     */
    static void copyLoopSpec(LoopStatement from, While to, Services services) {
        var repository = services.getSpecificationRepository();
        repository.copyLoopInvariant(from, to);
        var contracts = repository.getLoopContracts(from);
        if (contracts != null) {
            for (LoopContract contract : contracts) {
                repository.addLoopContract(contract.setLoop(to));
            }
        }
    }

    private static void addBodyStatements(List<Statement> target, Statement body) {
        if (body instanceof de.uka.ilkd.key.java.ast.StatementBlock block) {
            for (int i = 0; i < block.getStatementCount(); i++) {
                target.add(block.getStatementAt(i));
            }
        } else {
            target.add(body);
        }
    }

    private static LocalVariableDeclaration booleanDeclaration(ProgramVariable boolVar,
            Expression guard, Services services) {
        var booleanType = services.getJavaInfo().getKeYJavaType("boolean");
        return new LocalVariableDeclaration(new TypeRef(booleanType),
            new VariableSpecification(boolVar, guard, booleanType));
    }

    /** Rewrites target continues and preserves the rest of the body. */
    private static final class ContinueRewriter extends CreatingASTVisitor {
        private final ProgramVariable boolVar;
        private final Expression guard;
        private final List<Statement> prefix;
        private ProgramElement result;
        private int loopDepth = 0;

        private ContinueRewriter(Statement body, ProgramVariable boolVar, Expression guard,
                List<Statement> prefix, Services services) {
            super(body, true, services);
            this.boolVar = boolVar;
            this.guard = guard;
            this.prefix = prefix;
        }

        @Override
        public void start() {
            stack.push(new ExtList());
            walk(root());
            ExtList elements = stack.peek();
            int i = 0;
            while (!(elements.get(i) instanceof ProgramElement)) {
                i++;
            }
            result = (ProgramElement) elements.get(i);
        }

        ProgramElement result() {
            return result;
        }

        @Override
        protected void walk(ProgramElement node) {
            if (node instanceof LoopStatement) {
                loopDepth++;
            }
            super.walk(node);
            if (node instanceof LoopStatement) {
                loopDepth--;
            }
        }

        @Override
        public void performActionOnContinue(Continue x) {
            if (loopDepth == 0 && x.getLabel() == null) {
                var statements = new ArrayList<Statement>(prefix);
                statements.add(KeYJavaASTFactory.assign(boolVar, guard));
                statements.add(new Continue(x.getPositionInfo(), List.of(), null));
                addChild(KeYJavaASTFactory.block(statements.toArray(Statement[]::new)));
                changed();
            } else {
                doDefaultAction(x);
            }
        }
    }
}
