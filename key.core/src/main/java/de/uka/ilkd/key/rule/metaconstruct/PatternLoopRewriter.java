/**
 * Rewrites a loop with a binding guard into an ordinary loop with a boolean guard.
 *
 * <p>
 * For {@code while (e) S}, the result is
 *
 * <pre>
 * T p;                      // one temporary per tested expression
 * boolean b;
 * p = subject; b = e';      // e' is e with the tested expressions replaced by p
 * while (b) {
 *     whenTrue(e') declarations;
 *     block: { S with target continues rewritten to break block; }
 *     p = subject; b = e';
 * }
 * whenFalse(e') declarations, if the body has no unlabeled break
 * </pre>
 *
 * The tested expression is therefore evaluated exactly once per guard evaluation and the binding
 * uses that value. The guard refresh is placed after the body's labeled block, i.e. outside any
 * {@code try}/{@code finally}/{@code synchronized} statement that contained a {@code continue},
 * which keeps the evaluation at the position of the original {@code continue}. The rewritten guard
 * is a plain variable, so the rewrite rule cannot fire on the recursive loop generated by
 * unwinding.
 *
 * @author Alexander Weigl
 */
@TransformerMeta(name = "#rewritePatternBlock")
public final class PatternLoopRewriter extends ProgramTransformer {
    private final SchemaVariable statementsSV;

    /**
     * @param statementsSV the statement list of the block to rewrite
     */
    public PatternLoopRewriter(ProgramElement statementsSV) {
        super("#rewritePatternBlock", statementsSV);
        this.statementsSV = (SchemaVariable) statementsSV;
    }

    @Override
    public ImmutableList<ProgramElement> getArguments() {
        return ImmutableList.of((ProgramElement) statementsSV);
    }

    @Override
    public ProgramElement[] transform(ProgramElement pe, Services services,
            SVInstantiations svInst) {
        var statements = (ImmutableList<Statement>) svInst.getInstantiation(statementsSV);
        var result = new ArrayList<Statement>();
        boolean rewritten = false;
        for (Statement statement : statements) {
            if (!rewritten && statement instanceof LoopStatement loop
                    && BindingVariableVisitor.binds(loop.getGuardExpression())) {
                var boolVar = freshBoolean(services);
                for (ProgramElement element : rewriteLoop(loop, boolVar, services)) {
                    result.add((Statement) element);
                }
                rewritten = true;
            } else {
                result.add(statement);
            }
        }
        if (!rewritten) {
            var unchanged = new ProgramElement[statements.size()];
            for (int i = 0; i < statements.size(); i++) {
                unchanged[i] = statements.get(i);
            }
            return unchanged;
        }
        return result.toArray(ProgramElement[]::new);
    }

    private static ProgramElement[] rewriteLoop(LoopStatement loop, ProgramVariable boolVar,
            Services services) {
        if (loop instanceof While whileLoop) {
            return rewriteWhile(whileLoop, boolVar, services);
        } else if (loop instanceof For forLoop) {
            return rewriteFor(forLoop, boolVar, services);
        } else if (loop instanceof Do doLoop) {
            return rewriteDo(doLoop, boolVar, services);
        }
        throw new UnsupportedOperationException(
            "Unsupported loop kind in #rewritePatternBlock: " + loop.getClass().getSimpleName());
    }

    /**
     * The pieces of a rewritten loop: the declarations that must be visible to the after-loop
     * bindings, the guard evaluation before the loop, the loop itself and the after-loop bindings.
     */
    private record Rewritten(List<Statement> declarations, List<Statement> initial, While loop,
            List<Statement> after) {
    }

    /**
     * Rewrites a {@code while} loop. The returned array is meant to be spliced into the enclosing
     * statement block.
     */
    static ProgramElement[] rewriteWhile(While loop, ProgramVariable boolVar, Services services) {
        var rewritten = rewriteParts(loop, boolVar, services, List.of());
        var result = new ArrayList<Statement>();
        result.addAll(rewritten.declarations());
        result.addAll(rewritten.initial());
        result.add(rewritten.loop());
        result.addAll(rewritten.after());
        return result.toArray(ProgramElement[]::new);
    }

    /**
     * Rewrites a {@code for} loop. The for-init declarations stay in an inner block so they do not
     * leak; the after-loop declarations are outside that block.
     */
    static ProgramElement[] rewriteFor(For loop, ProgramVariable boolVar, Services services) {
        List<Statement> updates = new ArrayList<>();
        var updateExpressions = loop.getUpdates();
        if (updateExpressions != null) {
            for (Expression update : updateExpressions) {
                updates.add((ExpressionStatement) update);
            }
        }
        var rewritten = rewriteParts(loop, boolVar, services, updates);

        var initBlock = new ArrayList<Statement>();
        var initializers = loop.getInitializers();
        if (initializers != null) {
            for (var init : initializers) {
                if (init instanceof Statement statement) {
                    initBlock.add(statement);
                }
            }
        }
        initBlock.addAll(rewritten.initial());
        initBlock.add(rewritten.loop());

        var result = new ArrayList<Statement>();
        result.addAll(rewritten.declarations());
        result.add(KeYJavaASTFactory.block(initBlock.toArray(Statement[]::new)));
        result.addAll(rewritten.after());
        return result.toArray(ProgramElement[]::new);
    }

    /**
     * Rewrites a {@code do} loop by normalizing it with the existing unwind transformation and
     * rewriting the generated while. The declarations and the after-loop bindings stay outside the
     * normalized block so they are visible after the original {@code do}.
     */
    static ProgramElement[] rewriteDo(Do loop, ProgramVariable boolVar, Services services) {
        var inner = new ProgramElementName(services.getTermBuilder().newName("inner"));
        var outer = new ProgramElementName(services.getTermBuilder().newName("outer"));
        var transformation = new WhileLoopTransformation(loop, outer, inner, services);
        transformation.start();
        ProgramElement normalized = transformation.result();
        While generated = generatedWhile(normalized);
        if (generated == null) {
            return new ProgramElement[] { normalized };
        }
        var rewritten = rewriteParts(generated, boolVar, services, List.of());
        var replacement = KeYJavaASTFactory.block(
            concat(rewritten.initial(), List.of(rewritten.loop())).toArray(Statement[]::new));
        ProgramElement newNormalized =
            new ProgramElementReplacer((JavaProgramElement) normalized, services)
                    .replace(generated, replacement);

        var result = new ArrayList<ProgramElement>();
        result.addAll(rewritten.declarations());
        result.add(newNormalized);
        result.addAll(rewritten.after());
        return result.toArray(ProgramElement[]::new);
    }

    /**
     * Computes the rewrite of the given loop: the guard is evaluated into a boolean variable, the
     * tested expressions are evaluated once into temporaries and the binding and the refresh use
     * those temporaries. Target continues leave the body through a labeled block, so the refresh
     * runs at the loop's original guard position.
     *
     * @param loop the loop to rewrite
     * @param boolVar the fresh boolean variable provided by the rule
     * @param services the services
     * @param updates the for-updates to run on every continue, empty for other loops
     */
    private static Rewritten rewriteParts(LoopStatement loop, ProgramVariable boolVar,
            Services services, List<Statement> updates) {
        Expression guard = loop.getGuardExpression();
        Statement body = loop.getBody();
        var hoisted = hoist(guard, services);
        var bindings = BindingVariableVisitor.analyze(hoisted.guard());
        Expression strippedGuard = stripPatterns(hoisted.guard(), services);

        var exitLabel = freshLabel(services);
        Statement continued = rewriteContinues(body, exitLabel, services);
        Statement labeledBody = continued instanceof StatementBlock block ? block
                : KeYJavaASTFactory.block(continued);
        Statement rewrittenBody =
            new LabeledStatement(exitLabel, labeledBody, loop.getPositionInfo());

        var bodyStatements = new ArrayList<Statement>();
        bodyStatements.addAll(bindingDeclarations(bindings.whenTrue(), services));
        bodyStatements.add(rewrittenBody);
        bodyStatements.addAll(updates);
        bodyStatements.addAll(hoisted.evaluations());
        bodyStatements.add(KeYJavaASTFactory.assign(boolVar, strippedGuard));

        While newLoop = KeYJavaASTFactory.whileLoop(boolVar,
            KeYJavaASTFactory.block(bodyStatements.toArray(Statement[]::new)),
            loop.getPositionInfo());
        copyLoopSpec(loop, newLoop, services);

        var declarations = new ArrayList<Statement>(hoisted.declarations());
        declarations.add(declare(boolVar));

        var initial = new ArrayList<Statement>(hoisted.evaluations());
        initial.add(KeYJavaASTFactory.assign(boolVar, strippedGuard));

        var after = new ArrayList<Statement>();
        if (!bindings.whenFalse().isEmpty() && !hasUnlabeledBreak(body, services)) {
            after.addAll(bindingDeclarations(bindings.whenFalse(), services));
        }
        return new Rewritten(declarations, initial, newLoop, after);
    }

    /**
     * Converts the bindings into declarations. The internal equality assumptions produced by {@link
     * BindingVariableVisitor#toStatements} are omitted: the declaration already assigns the
     * tested value, and the assumptions would require JML parsing for the generated program.
     */
    private static List<Statement> bindingDeclarations(
            java.util.Map<LocationVariable, Expression> bindings, Services services) {
        var result = new ArrayList<Statement>();
        for (Statement statement : BindingVariableVisitor.toStatements(bindings, services)) {
            if (!(statement instanceof JmlAssert)) {
                result.add(statement);
            }
        }
        return result;
    }

    /**
     * Replaces every tested expression of an {@link InstanceofPattern} in {@code guard} by a fresh
     * temporary of the expression's static type, so that the guard, the binding and the refresh
     * share one evaluation. Returns the rewritten guard, the temporary declarations and the
     * assignments that evaluate the tested expressions.
     */
    private static Hoisted hoist(Expression guard, Services services) {
        var declarations = new ArrayList<LocalVariableDeclaration>();
        var evaluations = new ArrayList<TestedValue>();
        var taken = new LinkedHashSet<String>();
        var hoister = new SubjectHoister(guard, services, taken, declarations, evaluations);
        hoister.start();
        return new Hoisted((Expression) hoister.result(), declarations, evaluations);
    }

    private record Hoisted(Expression guard, List<LocalVariableDeclaration> declarations,
            List<TestedValue> testedValues) {
        List<Statement> evaluations() {
            var result = new ArrayList<Statement>(testedValues.size());
            for (TestedValue testedValue : testedValues) {
                result.add(KeYJavaASTFactory.assign(testedValue.variable(), testedValue.value()));
            }
            return result;
        }
    }

    private record TestedValue(LocationVariable variable, Expression value) {
    }

    private static TypeReference subjectType(Expression subject, Services services) {
        try {
            KeYJavaType type = subject.getKeYJavaType(services, null);
            if (type != null) {
                return new TypeRef(type);
            }
        } catch (RuntimeException ignored) {
            // a method call needs an execution context; Object is a valid supertype
        }
        return new TypeRef(services.getJavaInfo().getKeYJavaType("java.lang.Object"));
    }

    /**
     * Returns the while generated at the end of the do normalization. Selecting the last statement
     * of the normalized block avoids picking a nested while from the original do body.
     */
    private static While generatedWhile(ProgramElement normalized) {
        StatementBlock block = null;
        if (normalized instanceof StatementBlock statementBlock) {
            block = statementBlock;
        } else if (normalized instanceof LabeledStatement labeled
                && labeled.getBody() instanceof StatementBlock statementBlock) {
            block = statementBlock;
        }
        if (block == null || block.getStatementCount() == 0) {
            return null;
        }
        var last = block.getStatementAt(block.getStatementCount() - 1);
        return last instanceof While whileLoop ? whileLoop : null;
    }

    /**
     * Rewrites unlabeled continues that target the loop currently being rewritten to leave the
     * body's labeled block, so the guard refresh after the block runs outside any surrounding
     * {@code try}/{@code finally}/{@code synchronized} statement.
     *
     * <p>
     * A continue inside a nested loop targets that loop and is left untouched. A continue inside a
     * switch still targets the surrounding loop and is rewritten.
     */
    static Statement rewriteContinues(Statement body, Label exitLabel, Services services) {
        var rewriter = new ContinueRewriter(body, exitLabel, services);
        rewriter.start();
        return rewriter.result();
    }

    /**
     * Returns whether {@code body} contains an unlabeled break at loop depth zero, i.e. a break
     * for which the surrounding loop is the target.
     */
    static boolean hasUnlabeledBreak(Statement body, Services services) {
        var collector = new OuterBreakContinueAndReturnCollector(body, List.of(), services);
        collector.collect();
        return collector.getBreaks().stream().anyMatch(b -> b.getLabel() == null);
    }

    /**
     * Copies the loop specification and loop contracts from the original loop to the rewritten
     * loop.
     */
    static void copyLoopSpec(LoopStatement from, While to, Services services) {
        var repository = services.getSpecificationRepository();
        repository.copyLoopInvariant(from, to);
        var contracts = repository.getLoopContracts(from);
        if (contracts != null) {
            for (LoopContract contract : contracts) {
                repository.addLoopContract(contract.setLoop(to));
            }
        }
    }

    private static List<Statement> concat(List<Statement> first, List<Statement> second) {
        var result = new ArrayList<Statement>(first.size() + second.size());
        result.addAll(first);
        result.addAll(second);
        return result;
    }

    private static Label freshLabel(Services services) {
        return new ProgramElementName(
            TermBuilder.freeName("loop", services.getNamespaces(), Set.of()));
    }

    /**
     * Creates the loop's boolean guard variable. The name is selected with {@link
     * TermBuilder#freeName}, which does not mutate the global {@code NameRecorder}; the variable
     * enters the program through its declaration. The variable is only created for a loop that is
     * actually rewritten.
     */
    private static ProgramVariable freshBoolean(Services services) {
        var booleanType = services.getJavaInfo().getKeYJavaType("boolean");
        var name = new ProgramElementName(
            TermBuilder.freeName("b", services.getNamespaces(), Set.of()));
        return new LocationVariable(name, new TypeRef(booleanType));
    }

    private static LocalVariableDeclaration declare(ProgramVariable variable) {
        var type = new TypeRef(variable.getKeYJavaType());
        return new LocalVariableDeclaration(type, new VariableSpecification(variable));
    }

    /**
     * Returns a copy of {@code expression} with every {@link InstanceofPattern} replaced by a plain
     * {@link Instanceof}. The pattern declarations are provided by {@code #posBinding}; keeping
     * them in the body-end guard would declare the same variable a second time.
     */
    private static Expression stripPatterns(Expression expression, Services services) {
        var stripper = new PatternStripper(expression, services);
        stripper.start();
        return (Expression) stripper.result();
    }

    /** Rewrites target continues to a break of the loop body's labeled block. */
    private static final class ContinueRewriter extends CreatingASTVisitor {
        private final Label exitLabel;
        private Statement result;
        private int loopDepth = 0;

        private ContinueRewriter(Statement body, Label exitLabel, Services services) {
            super(body, true, services);
            this.exitLabel = exitLabel;
        }

        @Override
        public void start() {
            stack.push(new ExtList());
            walk(root());
            ExtList elements = stack.peek();
            int i = 0;
            while (!(elements.get(i) instanceof ProgramElement)) {
                i++;
            }
            result = (Statement) elements.get(i);
        }

        Statement result() {
            return result;
        }

        @Override
        protected void walk(ProgramElement node) {
            if (node instanceof LoopStatement) {
                loopDepth++;
            }
            super.walk(node);
            if (node instanceof LoopStatement) {
                loopDepth--;
            }
        }

        @Override
        public void performActionOnContinue(Continue x) {
            if (loopDepth == 0 && x.getLabel() == null) {
                addChild(new Break(x.getPositionInfo(), List.of(x.getComments()), exitLabel));
                changed();
            } else {
                doDefaultAction(x);
            }
        }
    }

    /** Replaces tested expressions by fresh temporaries of their static type. */
    private static final class SubjectHoister extends CreatingASTVisitor {
        private final Set<String> taken;
        private final List<LocalVariableDeclaration> declarations;
        private final List<TestedValue> testedValues;
        private ProgramElement result;

        private SubjectHoister(Expression expression, Services services, Set<String> taken,
                List<LocalVariableDeclaration> declarations, List<TestedValue> testedValues) {
            super(expression, true, services);
            this.taken = taken;
            this.declarations = declarations;
            this.testedValues = testedValues;
        }

        @Override
        public void start() {
            stack.push(new ExtList());
            walk(root());
            ExtList elements = stack.peek();
            int i = 0;
            while (!(elements.get(i) instanceof ProgramElement)) {
                i++;
            }
            result = (ProgramElement) elements.get(i);
        }

        ProgramElement result() {
            return result;
        }

        @Override
        public void performActionOnInstanceofPattern(InstanceofPattern x) {
            Expression subject = x.getExpressionAt(0);
            TypeReference type = subjectType(subject, services);
            String name = TermBuilder.freeName("subj", services.getNamespaces(), taken);
            taken.add(name);
            var temporary = new LocationVariable(new ProgramElementName(name), type);
            declarations.add(declare(temporary));
            testedValues.add(new TestedValue(temporary, subject));
            addChild(new InstanceofPattern(x.getPositionInfo(), List.of(x.getComments()), temporary,
                x.getTypeReference(), x.getPattern()));
            changed();
        }
    }

    /** Copies an expression while replacing instanceof patterns with plain instanceof. */
    private static final class PatternStripper extends CreatingASTVisitor {
        private ProgramElement result;

        private PatternStripper(Expression expression, Services services) {
            super(expression, true, services);
        }

        @Override
        public void start() {
            stack.push(new ExtList());
            walk(root());
            ExtList elements = stack.peek();
            int i = 0;
            while (!(elements.get(i) instanceof ProgramElement)) {
                i++;
            }
            result = (ProgramElement) elements.get(i);
        }

        ProgramElement result() {
            return result;
        }

        @Override
        public void performActionOnInstanceofPattern(InstanceofPattern x) {
            if (x.getPattern() instanceof RecordPattern) {
                addChild(BindingVariableVisitor.toTest(x));
            } else {
                addChild(new Instanceof(x.getPositionInfo(),
                    List.of(x.getComments()), x.getExpressionAt(0), x.getTypeReference()));
            }
            changed();
        }
    }
}
