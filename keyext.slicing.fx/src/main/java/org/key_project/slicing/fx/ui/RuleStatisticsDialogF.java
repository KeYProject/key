package org.key_project.slicing.fx.ui;

import java.util.ArrayList;
import java.util.Collection;
import java.util.Comparator;
import java.util.List;
import java.util.Optional;
import javafx.geometry.Insets;
import javafx.scene.Scene;
import javafx.scene.control.Button;
import javafx.scene.control.ButtonBar;
import javafx.scene.layout.BorderPane;
import javafx.scene.web.WebView;
import javafx.stage.Modality;
import javafx.stage.Window;

import org.key_project.slicing.RuleStatistics;
import org.key_project.slicing.RuleStatistics.RuleStatisticEntry;
import org.key_project.slicing.analysis.AnalysisResults;
import org.key_project.slicing.ui.HtmlFactory;

import org.jspecify.annotations.NullMarked;
import org.jspecify.annotations.Nullable;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/**
 * Dialog that displays the results of the dependency analysis algorithm, FX port of
 * {@code org.key_project.slicing.ui.RuleStatisticsDialog}: the rule statistics are shown as an
 * HTML table (generated by the reused {@link HtmlFactory#generateTable}) in the
 * {@link HtmlDialogF} WebView seam, with the four sort buttons of the Swing original
 * ("Sort by name", "Sort by total", "Sort by useless", "Sort by initial useless") that re-render
 * the table in the chosen order.
 */
@NullMarked
public final class RuleStatisticsDialogF extends javafx.stage.Stage {

    private static final Logger LOGGER = LoggerFactory.getLogger(RuleStatisticsDialogF.class);

    /** The rule statistics displayed in this dialog (Swing {@code RuleStatisticsDialog.stats}). */
    private final transient RuleStatistics statistics;

    /** The web view rendering the table; re-loaded on every sort-button press. */
    private final WebView webView;

    private RuleStatisticsDialogF(@Nullable Window owner, AnalysisResults results) {
        setTitle("Rule Statistics");
        this.statistics = results.ruleStatistics;
        if (owner != null) {
            initOwner(owner);
            initModality(Modality.NONE);
        }

        webView = new WebView();
        webView.setPrefSize(640, 380);
        webView.getEngine().loadContent(genTable(statistics,
            statistics.sortBy(
                Comparator.comparing(RuleStatisticEntry::numberOfApplications).reversed())),
            "text/html");

        // Swing RuleStatisticsDialog.constructButtonPanel: the four sort orders re-render the
        // table, Close disposes the dialog
        Button sortButton1 = new Button("Sort by name");
        sortButton1.setOnAction(e -> render(statistics.sortBy(
            Comparator.comparing(RuleStatisticEntry::ruleName))));
        Button sortButton2 = new Button("Sort by total");
        sortButton2.setOnAction(e -> render(statistics.sortBy(
            Comparator.comparing(RuleStatisticEntry::numberOfApplications).reversed())));
        Button sortButton3 = new Button("Sort by useless");
        sortButton3.setOnAction(e -> render(statistics.sortBy(
            Comparator.comparing(RuleStatisticEntry::numberOfUselessApplications).reversed())));
        Button sortButton4 = new Button("Sort by initial useless");
        sortButton4.setOnAction(e -> render(statistics.sortBy(
            Comparator.comparing(RuleStatisticEntry::numberOfInitialUselessApplications)
                    .reversed())));
        Button closeButton = new Button("Close");
        closeButton.setOnAction(e -> close());
        ButtonBar.setButtonData(closeButton, ButtonBar.ButtonData.OK_DONE);
        closeButton.setDefaultButton(true);

        ButtonBar buttonBar = new ButtonBar();
        buttonBar.getButtons().addAll(sortButton1, sortButton2, sortButton3, sortButton4,
            closeButton);
        BorderPane.setMargin(buttonBar, new Insets(10));

        BorderPane root = new BorderPane(webView, null, null, buttonBar, null);
        setScene(new Scene(root, 720, 520));
    }

    private void render(List<RuleStatisticEntry> entries) {
        LOGGER.debug("re-rendering the rule statistics table ({} entries)", entries.size());
        webView.getEngine().loadContent(genTable(statistics, entries), "text/html");
    }

    /** @return the web view showing the statistics table (verify harness seam) */
    public WebView getWebView() {
        return webView;
    }

    /**
     * Creates and shows the statistics dialog (Swing
     * {@code new RuleStatisticsDialog(window, results)}).
     *
     * @param owner owner window, may be {@code null}
     * @param results the analysis results to show
     * @return the shown dialog
     */
    public static RuleStatisticsDialogF show(@Nullable Window owner, AnalysisResults results) {
        RuleStatisticsDialogF dialog = new RuleStatisticsDialogF(owner, results);
        dialog.show();
        return dialog;
    }

    /**
     * Generate the HTML table to display in this dialog (Swing
     * {@code RuleStatisticsDialog.genTable}): a summary row for all rules, a summary row for the
     * branching rules, then one row per rule.
     *
     * @param statistics statistics on rule apps (needed for the branching-rule summary row)
     * @param rules the entries in the order they should appear
     * @return HTML
     */
    public static String genTable(RuleStatistics statistics, List<RuleStatisticEntry> rules) {
        List<String> columns = List.of("Rule name", "Total applications", "Useless applications",
            "Initial useless applications");

        List<Collection<String>> rows = new ArrayList<>();
        // summary row
        int uniqueRules = rules.size();
        int totalSteps = rules.stream().mapToInt(RuleStatisticEntry::numberOfApplications).sum();
        int uselessSteps =
            rules.stream().mapToInt(RuleStatisticEntry::numberOfUselessApplications).sum();
        int initialUseless =
            rules.stream().mapToInt(RuleStatisticEntry::numberOfInitialUselessApplications).sum();
        rows.add(List.of(String.format("(all %d rules)", uniqueRules),
            Integer.toString(totalSteps), Integer.toString(uselessSteps),
            Integer.toString(initialUseless)));
        // next summary row
        List<RuleStatisticEntry> rulesBranching =
            rules.stream().filter(it -> statistics.branches(it.ruleName())).toList();
        int uniqueRules2 = rulesBranching.size();
        totalSteps =
            rulesBranching.stream().mapToInt(RuleStatisticEntry::numberOfApplications).sum();
        uselessSteps =
            rulesBranching.stream().mapToInt(RuleStatisticEntry::numberOfUselessApplications)
                    .sum();
        initialUseless = rulesBranching.stream()
                .mapToInt(RuleStatisticEntry::numberOfInitialUselessApplications).sum();
        rows.add(List.of(String.format("(%d branching rules)", uniqueRules2),
            Integer.toString(totalSteps), Integer.toString(uselessSteps),
            Integer.toString(initialUseless)));
        rules.forEach(a -> {
            String name = a.ruleName();
            Integer all = a.numberOfApplications();
            Integer useless = a.numberOfUselessApplications();
            Integer iua = a.numberOfInitialUselessApplications();
            rows.add(List.of(name, all.toString(), useless.toString(), iua.toString()));
        });

        return HtmlFactory.generateTable(columns, new boolean[] { false, false, false, false },
            Optional.of(new String[] { null, "right", "right", "right" }), rows, null);
    }
}
